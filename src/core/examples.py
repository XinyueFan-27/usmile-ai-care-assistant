"""Demo 界面里的示例提问：全部是京东买家提问或评论原文（铁律 2、8）。

编号对照 data/processed（Q = 买家提问，R = 评论），用 eval/run_eval.py --check-quotes
或 src/check_quotes.py 核对。不要在这里加构造的句子。
"""

EXAMPLES = [
    ("Q020", "怎么连接手机？"),
    ("Q035", "刷头用多久会炸毛？"),
    ("Q089", "正畸带着皮套，能用吗？"),
    ("Q052", "续航多久呀"),
    ("Q012", "在海外的留子，连的上APP吗？"),
    ("Q002", "好用吗"),
    ("Q088", "默认模式是什么？能切换默认模式，下一次刷一起动还是想要的模式么？"),
    ("Q117", "轻柔模式能刷干净吗"),
    ("Q040", "飞利浦跟这个怎么选"),
    ("Q060", "冲不起电了，是更换还是维修，使用期限是多久？"),
    ("Q100", "请问这个是正品吗？"),
    ("R081", "我用了两个月后牙龈肿胀"),
]


def as_quote_markdown() -> str:
    """转成 check_quotes.py 能核对的格式：「原文」(编号)。"""
    return "\n".join(f"「{t}」({i})" for i, t in EXAMPLES)
